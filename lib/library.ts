export function getGuide(slug: string) {
  return guides.find((g) => g.slug === slug);
}

export function getAdjacentGuides(slug: string) {
  const idx = guides.findIndex((g) => g.slug === slug);
  if (idx === -1) return { prev: null, next: null };
  return {
    prev: idx > 0 ? guides[idx - 1] : null,
    next: idx < guides.length - 1 ? guides[idx + 1] : null,
  };
}

export function getCategoryLabel(id: string) {
  return guideCategories.find((c) => c.id === id)?.label || id;
}

export function formatGuideDate(date: string) {
  const d = new Date(date);
  const months = [
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
  ];
  return `${d.getDate()} ${months[d.getMonth()]} ${d.getFullYear()}`;
}
